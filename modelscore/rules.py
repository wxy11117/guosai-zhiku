CONFIG_PATH = Path(__file__).resolve().parent.parent / "config" / "cumcm-rules-v1.json"


def load_rules(path: Path = CONFIG_PATH) -> tuple[list[Rule], dict]:
    config = {"version": "cumcm-v1", "minimum_score": 45.0, "dimension_weights": {}}
    if path.exists():
        config.update(json.loads(path.read_text(encoding="utf-8")))
    overrides = config.get("rules", {})
    rules = []
    for rule in RULES:
        change = overrides.get(rule.id, {})
        rules.append(replace(rule, penalty=float(change.get("penalty", rule.penalty)), severity=change.get("severity", rule.severity)))
    return rules, config
